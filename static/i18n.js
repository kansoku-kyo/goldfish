// dev self-check: warn about any key missing from either language.
(function selfCheck() {
  if (typeof location === 'undefined') return;
  if (location.hostname !== 'localhost' && location.hostname !== '127.0.0.1') return;
  const enKeys = Object.keys(STRINGS.en);
  const jaKeys = Object.keys(STRINGS.ja);
  const all = new Set([...enKeys, ...jaKeys]);
  for (const k of all) {
    if (!(k in STRINGS.en)) console.warn(`i18n: missing en key "${k}"`);
    if (!(k in STRINGS.ja)) console.warn(`i18n: missing ja key "${k}"`);
  }
})();

export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'ja') return saved;
  } catch (e) { /* ignore */ }
  return (navigator.language || '').toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
}

export function t(key, vars) {
  const lang = getLang();
  const dict = STRINGS[lang] || STRINGS.en;
  let str = dict[key];
  if (str == null) str = (STRINGS.en[key] != null) ? STRINGS.en[key] : key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      str = str.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return str;
}

export function applyStatic(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
}
